#!/usr/bin/env python3
"""
ttf2gfx.py - convert a TTF/OTF font into an Adafruit-GFX-compatible C header
for use with drawText() on Pervasive Displays e-paper screens.

Usage:
  python3 ttf2gfx.py FONT.ttf LINE_HEIGHT NAME [--threshold 110] [--bold]

LINE_HEIGHT is the full ink height of a line in pixels: from the top of the
tallest glyph (e.g. Ä, l, f) to the bottom of the deepest one (g, j, y).

Characters: printable ASCII 0x20-0x7E, plus Latin-1 0xA0-0xFF (umlauts, ß ...),
plus the euro sign, which is stored in slot 0x80 (drawText maps U+20AC to it).
Glyphs missing from the font are stored empty.

Requires: pip install pillow fonttools
"""
import argparse, sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

FIRST, LAST = 0x20, 0xFF
EURO_SLOT = 0x80
MEASURE = "ÄÖÜÅÉÈbdfhklt|gjpqyÞ([{"   # characters used to measure the line extent


def char_for_slot(code):
    if code == EURO_SLOT:
        return "€"
    if 0x20 <= code <= 0x7E or 0xA0 <= code <= 0xFF:
        return chr(code)
    return None


def ink_extent(font, chars, thr):
    top, bottom = 10**6, -10**6
    for ch in chars:
        g = render(font, ch, thr)
        if g is None:
            continue
        _, _, _, h, _, yo = g
        top = min(top, yo)
        bottom = max(bottom, yo + h)
    return top, bottom


BOLD = False


def render(font, ch, thr):
    """Return (bits rows, width, ..., yOffset) for one glyph, relative to baseline."""
    pad = 200
    img = Image.new("L", (pad * 3, pad * 3), 0)
    d = ImageDraw.Draw(img)
    d.text((pad, pad * 2), ch, font=font, fill=255, anchor="ls")   # origin = left, baseline
    bw = img.point(lambda v: 255 if v >= thr else 0)
    if BOLD:                                   # thicken strokes by 1 px to the right
        from PIL import ImageChops
        bw = ImageChops.lighter(bw, ImageChops.offset(bw, 1, 0))
    box = bw.getbbox()
    if box is None:
        return None
    l, t, r, b = box
    crop = bw.crop(box)
    w, h = r - l, b - t
    rows = [[1 if crop.getpixel((x, y)) else 0 for x in range(w)] for y in range(h)]
    return rows, w, l - pad, h, None, t - pad * 2


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ttf"); ap.add_argument("height", type=int); ap.add_argument("name")
    ap.add_argument("--threshold", type=int, default=110,
                    help="0-255; lower keeps thin strokes thicker (default 110)")
    ap.add_argument("--bold", action="store_true", help="thicken strokes by 1 px")
    ap.add_argument("--preview", help=argparse.SUPPRESS)
    a = ap.parse_args()
    global BOLD
    BOLD = a.bold

    cmap = TTFont(a.ttf).getBestCmap()
    measure = [c for c in MEASURE if ord(c) in cmap]

    # find the largest point size whose ink extent fits the requested height
    lo, hi, best = 4, a.height * 4, 4
    while lo <= hi:
        mid = (lo + hi) // 2
        f = ImageFont.truetype(a.ttf, mid)
        t, b = ink_extent(f, measure, a.threshold)
        if b - t <= a.height:
            best, lo = mid, mid + 1
        else:
            hi = mid - 1
    font = ImageFont.truetype(a.ttf, best)
    top, bottom = ink_extent(font, measure, a.threshold)
    ascent = -top

    bitmap, glyphs, comments = [], [], []
    for code in range(FIRST, LAST + 1):
        ch = char_for_slot(code)
        adv = 0
        if ch is not None and ord(ch) in cmap:
            adv = int(round(font.getlength(ch)))
            g = render(font, ch, a.threshold)
        else:
            g = None
        off = len(bitmap)
        if g is None:
            glyphs.append((off, 0, 0, adv, 0, 0))
        else:
            rows, w, xo, h, _, yo = g
            bits = [bit for row in rows for bit in row]           # GFX: bits packed contiguously
            bits += [0] * (-len(bits) % 8)
            for i in range(0, len(bits), 8):
                v = 0
                for bit in bits[i:i + 8]:
                    v = (v << 1) | bit
                bitmap.append(v)
            glyphs.append((off, w, h, adv, xo, yo))
        label = "euro (U+20AC)" if code == EURO_SLOT else (repr(ch) if ch else "unused")
        comments.append(f"0x{code:02X} {label}")

    yadv = a.height + max(2, a.height // 10)
    n = a.name
    out = []
    out.append(f"// {n}.h - generated by ttf2gfx.py from {a.ttf.split('/')[-1]}")
    out.append(f"// Line ink height {a.height} px (ascent {ascent}, descent {bottom}), point size {best}, threshold {a.threshold}{', bold' if a.bold else ''}")
    out.append(f"// Characters 0x{FIRST:02X}-0x{LAST:02X} (Latin-1), euro sign in slot 0x{EURO_SLOT:02X}")
    out.append("// Format: Adafruit GFX font (GFXfont / GFXglyph); draw with drawText() from drawText.h")
    nm=TTFont(a.ttf)["name"]
    family=nm.getDebugName(1) or "unknown"
    copyright_=nm.getDebugName(0) or "see the original font"
    licence=nm.getDebugName(13) or "see the original font"
    out.append("//")
    out.append(f"// Font: {family}")
    out.append(f"// {copyright_}")
    out.append(f"// {licence}")
    out.append("// This file is a modified version (bitmap conversion) of that font and is")
    out.append("// distributed under the same license; see THIRD_PARTY_NOTICES.md.")
    out.append("// SPDX-License-Identifier: OFL-1.1")
    if "reserved font name" in copyright_.lower():
        import re as _re
        rfn=_re.findall(r'Reserved Font Names?\s*"([^"]+)"', copyright_, _re.I)
        print(f"WARNING: this font has a Reserved Font Name ({', '.join(rfn) or 'see copyright'}).\n"
              f"         A converted (bitmap) font is a Modified Version under the OFL and must not use\n"
              f"         that name. Pick a NAME without it, e.g. a neutral name like 'BadgeWide25'.")
        if any(r.lower().replace(' ','') in n.lower() for r in rfn):
            print(f"         -> your NAME '{n}' contains the reserved name; please choose another one.")
    out.append("#pragma once")
    out.append('#include "drawText.h"\n')
    out.append(f"#define {n.upper()}_ASCENT {ascent}   // baseline offset from the top of the line box\n")
    out.append(f"const uint8_t {n}Bitmaps[] = {{")
    for i in range(0, len(bitmap), 16):
        out.append("  " + ", ".join(f"0x{v:02X}" for v in bitmap[i:i + 16]) + ",")
    out.append("};\n")
    out.append(f"const GFXglyph {n}Glyphs[] = {{")
    out.append("  // bitmapOffset, width, height, xAdvance, xOffset, yOffset")
    for g, cmt in zip(glyphs, comments):
        out.append(f"  {{ {g[0]:5d}, {g[1]:3d}, {g[2]:3d}, {g[3]:3d}, {g[4]:4d}, {g[5]:4d} }},   // {cmt}")
    out.append("};\n")
    out.append(f"const GFXfont {n} = {{ (uint8_t *){n}Bitmaps, (GFXglyph *){n}Glyphs, 0x{FIRST:02X}, 0x{LAST:02X}, {yadv} }};")
    out.append(f"// Bitmap {len(bitmap)} bytes + glyph table {len(glyphs) * 8} bytes")
    with open(f"{n}.h", "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"{n}.h: point size {best}, ascent {ascent}, descent {bottom}, line advance {yadv}, "
          f"bitmap {len(bitmap)} B, glyphs {len(glyphs)}")



if __name__ == "__main__":
    main()
